export function ProvBadges({ provenance }: { provenance: string }) {
  const codes = provenance.split(";").map((p) => PROV_BY_NAME[p]).filter(Boolean);
  if (!codes.length) return <span className="muted">-</span>;
  return <span className="prov-set">{codes.map((c) => <span key={c} className={`prov prov-${c}`} title={PROV[c].long}>{PROV[c].label}</span>)}</span>;
}

const MODULES: Record<string, string> = {
  A: "Identity and mission", B: "Anthropometrics and vitals", C: "Medical history", D: "Laboratory baseline",
  E: "Genetics", F: "Fitness and bone", G: "Neuro-ocular", H: "Sleep and chronotype", I: "Motion sickness",
  J: "Psychological profile", K: "Cognitive baseline", L: "Nutrition", M: "Preferences", C_: "Daily check-in",
};
const GROUP_LABEL: Record<string, string> = { labs: "Labs", exams: "One-off exams", daily: "Daily streams" };

function fmt(v: number | string | null | undefined, unit = ""): string {
  if (v === null || v === undefined || v === "") return "-";
  if (typeof v === "number") {
    const s = Math.abs(v) >= 100 ? v.toFixed(0) : Math.abs(v) >= 10 ? v.toFixed(1) : v.toFixed(2);
    const u = prettyUnit(unit);
    // Score ranges ("1-7") and codes ("1=pos") are not units.
    return `${s.replace(/\.0+$|(\.\d*?)0+$/, "$1")}${u && !/^\d+-\d+$|=/.test(u) ? ` ${u}` : ""}`;
  }
  return String(v);
}

/** "lo-hi", or "lo to hi" when a bound is negative (avoids "-2.8--1.4"). */
export const rangeText = (lo: number, hi: number, unit = "") =>
  `${fmt(lo)}${lo < 0 || hi < 0 ? " to " : "-"}${fmt(hi, unit)}`;

/** Six-month mini chart: range band, baseline, values (dots when sparse). */
function Spark({ pts, band, base, start }: { pts: PrePoint[]; band: Band | null; base: number | null; start: number }) {
  if (pts.length < 2) return <svg className="spark" viewBox="0 0 200 36" aria-hidden="true" />;
  const vals = [...pts.map((p) => p.v), ...(band ? [band.lo, band.hi] : []), ...(base !== null ? [base] : [])];
  const lo = Math.min(...vals), hi = Math.max(...vals), pad = (hi - lo) * 0.1 || 1;
  const x = (t: number) => ((t - start) / (0 - start)) * 196 + 2;
  const y = (v: number) => 34 - ((v - (lo - pad)) / (hi - lo + 2 * pad)) * 32;
  const sparse = pts.length <= 30;
  return (
    <svg className="spark" viewBox="0 0 200 36" aria-hidden="true">
      {band && <rect className="spark-band" x={0} width={200} y={y(band.hi)} height={Math.max(1, y(band.lo) - y(band.hi))} />}
      {base !== null && <line className="spark-base" x1={0} x2={200} y1={y(base)} y2={y(base)} />}
      <polyline className="spark-line" points={pts.map((p) => `${x(p.t).toFixed(1)},${y(p.v).toFixed(1)}`).join(" ")} />
      {sparse && pts.map((p, i) => <circle key={i} className={p.p === "SC" ? "dot-model" : "dot-real"} cx={x(p.t)} cy={y(p.v)} r={2.4} />)}
    </svg>
  );
}

function Stream({ doc, m, onOpen }: { doc: PassportDoc; m: MetricDef; onOpen: (key: string) => void }) {
  const pts = doc.series[preKey(m)];
  const field = fieldFor(doc, preKey(m));
  const unit = metricUnit(m, doc);
  const title = metricLabel(m, doc);
  const data = useMemo(() => {
    const byT = new Map<number, { t: number; real?: number; model?: number; all?: number }>();
    for (const [t, v, p] of pts ?? []) {
      const row = byT.get(t) ?? { t };
      if (p === "SC") row.model = v; else row.real = v;
      row.all = v;
      byT.set(t, row);
    }
    return [...byT.values()].sort((a, b) => a.t - b.t);
  }, [pts]);
  if (!pts?.length) return null;
  const vals = data.map((d) => d.all as number);
  const lo = field?.lo ?? null, hi = field?.hi ?? null, base = typeof field?.value === "number" ? field.value : null;
  const all = [...vals, ...[lo, hi, base].filter((v): v is number => typeof v === "number")];
  const pad = (Math.max(...all) - Math.min(...all)) * 0.12 || 1;
  const yMin = Math.min(...all) - pad, yMax = Math.max(...all) + pad;
  const realN = pts.filter((p) => p[2] !== "SC").length;
  const sparse = pts.length <= 30;
  const small = Math.abs(yMax - yMin) < 6;
  return (
    <div className="stream">
      <div className="stream-h">
        <button type="button" className="linkbtn stream-title" onClick={() => onOpen(m.key)} title="Open in Health dynamics">{title}</button>
        <span className="muted mono">{base !== null ? `baseline ${fmt(base, unit)}` : ""}</span>
      </div>
      <div className="stream-chart">
        <ResponsiveContainer width="100%" height="100%">
          <LineChart data={data} margin={{ top: 6, right: 8, bottom: 0, left: Math.min(...all) < 0 ? -6 : -18 }}>
            <CartesianGrid strokeDasharray="3 3" vertical={false} />
            <XAxis dataKey="t" type="number" domain={[doc.window.start, 0]} ticks={[-180, -120, -60, 0]}
              tickFormatter={(t) => (t === 0 ? "launch" : `L${t}`)} />
            <YAxis domain={[small ? Number(yMin.toFixed(2)) : Math.floor(yMin), small ? Number(yMax.toFixed(2)) : Math.ceil(yMax)]} width={48}
              allowDecimals={small} tickFormatter={(v: number) => (Math.abs(v) >= 1000 ? `${Math.round(v / 1000)}k` : small ? String(Number(v.toFixed(2))) : String(Math.round(v)))} />
            {lo !== null && hi !== null && <ReferenceArea y1={lo} y2={hi} className="band" ifOverflow="extendDomain" />}
            {base !== null && <ReferenceLine y={base} className="base" ifOverflow="extendDomain" />}
            <Tooltip content={({ active, payload, label }) => {
              if (!active || !payload?.length) return null;
              const row = payload[0].payload as { real?: number; model?: number };
              const v = row.real ?? row.model;
              return <div className="trend-tip"><b>{fmt(v ?? null, unit)}</b> · L{label} · {row.real !== undefined ? "real" : "calibrated model"}</div>;
            }} />
            <Line dataKey="all" className="stream-line" dot={false} connectNulls={false} isAnimationActive={false} />
            <Line dataKey="model" stroke="none" dot={{ r: sparse ? 4 : 1.8, className: "dot-model" }} activeDot={false} isAnimationActive={false} />
            <Line dataKey="real" stroke="none" dot={{ r: sparse ? 4.5 : 2.2, className: "dot-real" }} activeDot={false} isAnimationActive={false} />
          </LineChart>
        </ResponsiveContainer>
      </div>
      <p className="stream-cap muted">
        {realN} real · {pts.length - realN} modelled{lo !== null && hi !== null ? ` · ${m.group === "labs" ? "range" : "personal range"} ${rangeText(lo, hi, unit)}` : ""}
        {field?.trend_per_30d != null ? ` · trend ${field.trend_per_30d > 0 ? "+" : ""}${fmt(field.trend_per_30d)} / 30 d` : ""}
      </p>
    </div>
  );
}

/** All passport series, grouped like the Health dynamics window. */
function SeriesTab({ doc, onOpen }: { doc: PassportDoc; onOpen: (key: string) => void }) {
  const groups = useMemo(() => {
    const known = new Set<string>();
    const out: { id: GroupId | "other"; label: string; metrics: MetricDef[] }[] = GROUPS.map((g) => {
      const metrics = METRICS.filter((m) => m.group === g.id && doc.series[preKey(m)]?.length);
      metrics.forEach((m) => known.add(preKey(m)));
      return { id: g.id, label: g.label, metrics };
    });
    const other = Object.keys(doc.series).filter((k) => !known.has(k) && doc.series[k].length).map((k) => ({ ...metricDef(k), key: k }));
    if (other.length) out.push({ id: "other", label: "Other", metrics: other });
    return out.filter((g) => g.metrics.length);
  }, [doc]);
  return (
    <>
      <p className="muted pp-note">Filled dots: real measurements. Hollow dots: calibrated model (days before the donor's record starts, check-ins and tests with no open data). Band: personal range (p10-p90) or the lab reference range. Gaps are days with no data. Click a title to follow it into the mission in Health dynamics.</p>
      {groups.map((g) => (
        <section key={g.id} className="pp-group">
          <h3>{g.label} <span className="muted">· {g.metrics.length}</span></h3>
          <div className="streams">{g.metrics.map((m) => <Stream key={m.key} doc={doc} m={m} onOpen={onOpen} />)}</div>
        </section>
      ))}
    </>
  );
}

function SessionsTab({ doc }: { doc: PassportDoc }) {
  const byT = useMemo(() => {
    const g = new Map<number, PassportDoc["sessions"]>();
    for (const s of [...doc.sessions].sort((a, b) => a.t - b.t)) g.set(s.t, [...(g.get(s.t) ?? []), s]);
    return [...g.entries()];
  }, [doc]);
  const label = (k: string) => { const f = fieldFor(doc, k); return { name: f?.label ?? k, unit: f?.unit ?? "" }; };
  return (
    <>
      <p className="muted pp-note">Pre-flight medical schedule as this crew member went through it: {doc.sessions.length} sessions, {doc.sessions.reduce((n, s) => n + Object.keys(s.values).length, 0)} recorded values. L-x = days before launch.</p>
      <ol className="s-timeline">
        {byT.map(([t, list]) => (
          <li key={t}>
            <span className="mono s-t">L{t}</span>
            <div className="s-day">
              {list.map((s) => (
                <div key={s.session_id} className={`s-card ${s.status !== "done" ? "pf-missing" : ""}`}>
                  <div className="s-head">
                    <b>{s.title}</b>
                    {s.status !== "done" && <span className="ready ready-missing">{s.status.replace(/-/g, " ")}</span>}
                    {s.provenance && <ProvBadges provenance={s.provenance} />}
                  </div>
                  {Object.keys(s.values).length > 0 ? (
                    <dl className="s-vals">
                      {Object.entries(s.values).map(([k, v]) => {
                        const l = label(k);
                        return <div key={k}><dt>{l.name}</dt><dd className="mono">{fmt(v as number | string, l.unit)}</dd></div>;
                      })}
                    </dl>
                  ) : <p className="muted s-none">{s.status === "done" ? "Done · no single values in the open data (daily streams carry this period)." : "No open data source yet."}</p>}
                  {s.source_ids && <p className="muted pf-method">Source: {s.source_ids.split(";").join(", ")}</p>}
                </div>
              ))}
            </div>
          </li>
        ))}
      </ol>
    </>
  );
}

function FieldsTable({ fields }: { fields: PassportField[] }) {
  const groups = useMemo(() => {
    const g = new Map<string, PassportField[]>();
    for (const f of fields) {
      const key = f.field_id === "CHECKIN" ? "C_" : f.field_id[0];
      g.set(key, [...(g.get(key) ?? []), f]);
    }
    return [...g.entries()].sort(([a], [b]) => (a === "C_" ? "Z" : a).localeCompare(b === "C_" ? "Z" : b));
  }, [fields]);
  return (
    <div className="pf-table">
      {groups.map(([mod, rows]) => (
        <section key={mod} className="pf-mod">
          <h3><code>{mod === "C_" ? "✓" : mod}</code> {MODULES[mod] ?? mod}</h3>
          <table>
            <thead><tr><th>Field</th><th>Value</th><th>Personal / lab range</th><th>Trend / 30 d</th><th>Data</th><th>Source</th></tr></thead>
            <tbody>
              {rows.map((f, i) => (
                <tr key={`${f.field_id}-${f.metric}-${i}`} className={f.readiness === "missing" ? "pf-missing" : ""}>
                  <td><code>{f.field_id === "CHECKIN" ? "" : f.field_id}</code> {f.label}</td>
                  <td className="mono">{fmt(f.value, f.unit)}</td>
                  <td className="mono">{f.lo !== null && f.hi !== null ? rangeText(f.lo, f.hi) : "-"}</td>
                  <td className="mono">{f.trend_per_30d != null ? `${f.trend_per_30d > 0 ? "+" : ""}${fmt(f.trend_per_30d)}` : "-"}</td>
                  <td>
                    <span className={`ready ready-${f.readiness}`}>{f.readiness}</span>
                    {f.n > 1 && <span className="muted"> · n={f.n}</span>}
                    <div className="muted pf-method">{f.method}</div>
                  </td>
                  <td><ProvBadges provenance={f.provenance} /><div className="muted pf-method">{f.source_ids.split(";").join(", ")}</div></td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      ))}
    </div>
  );
}

/** Baselines the rule engine uses, each with its range and the six-month mini chart. */
function BaselineTiles({ passport, doc, onOpen }: { passport: Passport; doc: PassportDoc | null; onOpen: (key: string) => void }) {
  const order = (k: string) => { const i = METRICS.findIndex((m) => m.key === k); return i < 0 ? 999 : i; };
  const keys = [...new Set([...Object.keys(passport.baselines), ...Object.keys(passport.personal_ranges ?? {})])]
    .filter((k) => typeof passport.baselines[k] === "number" || passport.personal_ranges?.[k]?.lo != null)
    .sort((a, b) => order(a) - order(b));
  return (
    <div className="pp-tiles">
      {keys.map((k) => {
        const m = metricDef(k);
        const unit = metricUnit(m, doc);
        const band = bandOf(m, passport, doc);
        const base = typeof passport.baselines[k] === "number" ? passport.baselines[k] : null;
        const f = fieldFor(doc, preKey(m)) ?? (m.session ? fieldFor(doc, m.session) : undefined);
        const pts = preflightPoints(m, doc);
        const shown = base ?? (typeof f?.value === "number" ? f.value : null);
        return (
          <button key={k} type="button" className="pp-tile" onClick={() => onOpen(k)}>
            <span className="eyebrow">{metricLabel(m, doc)}</span>
            <b className="v">{withUnit(shown, { ...m, digits: m.digits ?? 1 }, unit)}</b>
            <span className="muted r">
              {band ? `${band.kind === "lab" ? "lab range" : "personal range"} ${rangeText(band.lo, band.hi)}` : "no range yet"}
              {f && f.n > 1 ? ` · n=${f.n}` : ""}
              {f?.trend_per_30d != null ? ` · ${f.trend_per_30d > 0 ? "+" : ""}${fmt(f.trend_per_30d)} / 30 d` : ""}
            </span>
            {doc && <Spark pts={pts} band={band} base={base} start={doc.window.start} />}
          </button>
        );
      })}
    </div>
  );
}

function Overview({ passport, doc, err, onOpen, onImport }: { passport: Passport; doc: PassportDoc | null; err: string | null; onOpen: (key: string) => void; onImport?: () => void }) {
  const counts = useMemo(() => {
    const c: Record<string, number> = {};
    for (const pts of Object.values(doc?.series ?? {})) for (const p of pts) c[p[2]] = (c[p[2]] ?? 0) + 1;
    return c;
  }, [doc]);
  const a = passport.astronaut;
  const sex = doc?.sex ?? a.sex, age = doc?.age ?? a.age;
  return (
    <div className="pp-overview">
      <p className="pp-lead">
        {a.role}{sex ? ` · ${sex === "F" ? "female" : "male"}` : ""}{age ? `, ${age}` : ""} · {a.id} · {passport.mission.vehicle}
        {isLocalRef(passport.passport_ref) ? ` · six-month data imported from ${doc?.import?.filename ?? "your file"}. Every value keeps its origin.`
          : passport.passport_ref ? " · fictional crew member built from real, de-identified donors. Every value keeps its origin." : ""}
      </p>
      {!passport.passport_ref && (
        <div className="banner neutral" role="note"><div><b>No six-month passport yet.</b>{(passport.baselines_source ?? "Baselines are population defaults until 7 days of check-ins").replace(/\.?$/, ".")} Health dynamics shows your own check-ins as they come in.</div>
          {onImport && <button type="button" className="btn btn-sm" onClick={onImport}>Import six-month data</button>}</div>
      )}
      {err && <div className="banner" role="alert"><div><b>Could not load the six-month passport.</b> {err}</div></div>}
      {passport.passport_ref && !doc && !err && <p className="updating"><span className="spinner" />Loading six-month data…</p>}
      <section className="pp-sec">
        <h3>Baselines the rule engine compares against</h3>
        <BaselineTiles passport={passport} doc={doc} onOpen={onOpen} />
        {passport.baselines_source && <p className="muted pp-note">Baselines: {passport.baselines_source}</p>}
      </section>
      <div className="pp-cols">
        <section className="pp-sec">
          <h3>Active modifiers</h3>
          <ModifierList passport={passport} />
          {passport.countermeasures.length > 0 && <p className="muted pp-note">Helpers: {passport.countermeasures.join(", ")}</p>}
          <PreflightTimeline passport={passport} />
        </section>
        {doc && (
          <section className="pp-sec">
            <h3>{doc.import ? "Data source" : "Data donors"}</h3>
            {doc.import && (
              <div className="donors">
                <div className="donor">
                  <p className="eyebrow">Imported file</p>
                  <b className="mono">{doc.import.filename}</b>
                  <span className="muted">{doc.import.used} values · L{doc.import.first} → L{doc.import.last}{doc.import.lab_ref_fallback.length > 0 ? ` · standard lab ranges for ${doc.import.lab_ref_fallback.join(", ")}` : ""}</span>
                </div>
              </div>
            )}
            <div className="donors">
              {doc.donors.map((d) => (
                <div key={d.field_group} className="donor">
                  <p className="eyebrow">{GROUP_LABEL[d.field_group] ?? d.field_group}</p>
                  <b className="mono">{d.donor_subject_id}</b>
                  <span className="muted">{d.note}</span>
                </div>
              ))}
            </div>
            <div className="prov-legend" aria-label="Data origin legend: points per origin">
              {(Object.keys(PROV) as ProvCode[]).map((c) => (
                <span key={c}><span className={`prov prov-${c}`} title={PROV[c].long}>{PROV[c].label}</span>{counts[c] ? <span className="muted mono"> {counts[c]}</span> : null}</span>
              ))}
            </div>
          </section>
        )}
      </div>
    </div>
  );
}

type Tab = "overview" | "series" | "sessions" | "fields";

/** Full-screen passport: overview, every six-month series, the pre-flight sessions and every field with its origin. */
export function PassportWindow({ passport, onClose, onEdit, onCharts, onRemove, onImport }: {
  passport: Passport; onClose: () => void; onEdit: () => void; onCharts: (metric?: string) => void; onRemove?: () => void;
  /** "My crew": import six-month data or check-ins from a file into this member. */
  onImport?: () => void;
}) {
  const ref = passport.passport_ref ?? null;
  const [doc, setDoc] = useState<PassportDoc | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [tab, setTab] = useState<Tab>("overview");
  useEffect(() => {
    setDoc(null); setErr(null);
    if (!ref) return;
    let live = true;
    getCrewPassport(ref).then((d) => { if (live) setDoc(d); }).catch((e) => { if (live) setErr(e instanceof Error ? e.message : String(e)); });
    return () => { live = false; };
  }, [ref]);
  useEffect(() => { if (!ref) setTab("overview"); }, [ref]);

  const nSeries = doc ? Object.values(doc.series).filter((s) => s.length).length : 0;
  const tabs: [Tab, string][] = doc
    ? [["overview", "Overview"], ["series", `Charts (${nSeries})`], ["sessions", `Sessions (${doc.sessions.length})`], ["fields", `Fields (${doc.fields.length})`]]
    : [];

  return (
    <Modal variant="full" title={`${passport.astronaut.name} · passport`}
      eyebrow={ref ? "Six-month pre-flight passport · L-180 → launch" : "Personal passport"}
      onClose={onClose}
      actions={<>
        <button type="button" className="btn btn-primary btn-sm" onClick={() => onCharts()}>Health dynamics</button>
        <button type="button" className="btn btn-secondary btn-sm" onClick={onEdit}>Edit passport</button>
        {onImport && <button type="button" className="btn btn-secondary btn-sm" onClick={onImport}>Import data</button>}
        {onRemove && <button type="button" className="btn btn-secondary btn-sm" onClick={onRemove}>Remove from crew</button>}
      </>}>
      <div className="pp-data">
        {tabs.length > 0 && (
          <div className="tabs pp-tabs" role="tablist" aria-label="Passport view">
            {tabs.map(([k, l]) => (
              <button key={k} role="tab" type="button" className="tab" aria-selected={tab === k} onClick={() => setTab(k)}>{l}</button>
            ))}
          </div>
        )}
        {tab === "overview" && <Overview passport={passport} doc={doc} err={err} onOpen={onCharts} onImport={onImport} />}
        {tab === "series" && doc && <SeriesTab doc={doc} onOpen={onCharts} />}
        {tab === "sessions" && doc && <SessionsTab doc={doc} />}
        {tab === "fields" && doc && <FieldsTable fields={doc.fields} />}
      </div>
    </Modal>
  );
}
