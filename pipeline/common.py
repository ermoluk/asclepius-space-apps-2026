def write_table(name: str, rows: list[dict]) -> Path:
    """Write a warehouse table; rows are dicts keyed by SCHEMA[name]. Deterministic order is the caller's job."""
    cols = SCHEMA[name]
    WAREHOUSE.mkdir(parents=True, exist_ok=True)
    path = WAREHOUSE / f"{name}.csv"
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="raise")
        w.writeheader()
        for r in rows:
            w.writerow({c: _fmt(r.get(c)) for c in cols})
    return path


def read_table(name: str) -> list[dict]:
    path = WAREHOUSE / f"{name}.csv"
    if not path.exists():
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _fmt(v):
    if v is None:
        return ""
    if isinstance(v, float):
        return f"{v:.6g}"
    if isinstance(v, (list, tuple)):
        return ";".join(str(x) for x in v)
    return v


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def age_band(age: float | None) -> str:
    if age is None:
        return ""
    lo = int(age // 10 * 10)
    return f"{lo}-{lo + 9}"
